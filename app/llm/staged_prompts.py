def section(title: str, body: str) -> str:
    return f"{title}:\n{body}" if body.strip() else ""


def message(*parts: str, text: str) -> str:
    """One user turn: the context blocks that are not empty, then the message in quotes."""
    blocks = [p for p in parts if p]
    blocks.append(f"{H_MESSAGE}:\n«{text.strip()}»")
    return "\n\n".join(blocks)


def keyed(lines: dict[str, str]) -> str:
    return "\n".join(f"{key}: {label}" for key, label in lines.items())
