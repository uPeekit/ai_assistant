def linker_message(body: str, candidates: list[str], already: list[str]) -> str:
    payload = {
        "текст_заметки": body,
        "существующие_заметки": candidates,
        "уже_связано": already,
    }
    return json.dumps(payload, ensure_ascii=False, indent=1)


