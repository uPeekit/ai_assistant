def site_guide(sites) -> str:
    """The owner's sites by category. Those marked * have a direct search (site_search); the
    rest are found with web_search and read with read."""
    lines = ["Сайты пользователя по категориям (* — есть site_search):"]
    for kind in [*SITE_KINDS, *sorted({s.kind for s in sites} - set(SITE_KINDS))]:
        names = [f"{s.name}*" + (" (продажа и аренда)" if s.rent_template else "")
                 for s in sites if s.kind == kind and s.template]
        names += [s.name for s in sites if s.kind == kind and not s.template]
        if names:
            lines.append(f"- {SITE_KINDS.get(kind, kind)}: {', '.join(names)}")
    return "\n".join(lines)


